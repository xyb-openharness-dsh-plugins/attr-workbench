/* ATTR 工作台 · 0004：照护者记录（caregiver_rows）。

 * 为什么必须新开迁移：0001/0002/0003 已冻结（sha256 在 schema/freeze-contract.md），
 * 结构变更只能追加。0.4.0 在「生活与照护 → 情绪与照护者」里留了一块空位并写明
 * 「现有 29 张表里没有它」——这一支就是把那块空位补上。
 *
 * 为什么不能塞进已有表：
 * 1. `daily_rows.kind` 的 CHECK 只允许 饮食/体重/活动/出行，写不进「照护」；
 *    放宽这个 CHECK 等于改 0001 的字节，违反冻结规则第一条。
 * 2. `viewpoints` 是"我的看法"，一行一个心境片段，没有位置放"谁在照顾我、能不能替手"；
 *    硬塞会把两类事实混成一层（四条契约第 4 条：事实四层不合并）。
 * 3. `family_rows` 记的是家系成员的**检测状态**（是否携带变异），不是照护负担；
 *    两者会同时提到同一个人，但一个是遗传风险、一个是每天的累，不能共用一行。
 *
 * 列的口径（照 writes.js 的「空 ≠ 阴性」）：
 * - 除 profile_key 外全部可空、无默认值：没填就是 NULL，不折算成「没有」。
 *   `backup`（有没有人可以替手）尤其如此——「问了但没人」与「没记」是两件事，
 *   前者是用户明确写下的答案，后者是这一栏空着，界面要能分辨。
 * - `private INTEGER DEFAULT 1` 与 `family_rows` 一致：照护安排属私密层，默认不进摘要。
 *   注意导出不是靠这个字段兜底的——`dsh/export.js` 是**只读白名单**，这张表不在白名单里，
 *   所以默认不进导出、也不进 AI 草稿。
 * - 只记称呼不记真名（`who`），与 `counsel_rows`「只记角色，不记姓名」的写法一致。
 *
 * 这一支不动任何已冻结的表：没有 ALTER，只有一张新表。
 */

CREATE TABLE caregiver_rows (
  profile_key TEXT,
  d           TEXT,             -- 这一条是哪天的情况（YYYY-MM-DD）
  who         TEXT,             -- 谁在照顾你：称呼，可匿名（"女儿""大姐"）
  relation    TEXT,             -- 与你的关系：配偶 / 子女 / 父母 / 兄弟姐妹 / 其他
  burden      TEXT,             -- 这一周最累的一件事（用户原话，不做归类）
  backup      TEXT,             -- 有没有人可以替手：用户自己的答案，空 = 没记
  need        TEXT,             -- 你自己需要什么（"想有人替我半天"这类原话）
  private     INTEGER DEFAULT 1,
  ord         INTEGER
);
